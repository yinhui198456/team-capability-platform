def _add_fk(
    connection: psycopg.Connection,
    table: str,
    constraint: str,
    definition: str,
) -> None:
    connection.execute(
        f"""
        DO $$ BEGIN
            IF NOT EXISTS (
                SELECT 1 FROM pg_constraint
                WHERE conrelid = '{table}'::regclass AND conname = '{constraint}'
            ) THEN
                ALTER TABLE {table} ADD CONSTRAINT {constraint} {definition};
            END IF;
        END $$
        """
    )


def _add_check(
    connection: psycopg.Connection,
    table: str,
    constraint: str,
    expression: str,
) -> None:
    connection.execute(
        f"""
        DO $$ BEGIN
            IF NOT EXISTS (
                SELECT 1 FROM pg_constraint
                WHERE conrelid = '{table}'::regclass AND conname = '{constraint}'
            ) THEN
                ALTER TABLE {table} ADD CONSTRAINT {constraint} CHECK ({expression});
            END IF;
        END $$
        """
    )


def _create_planning_snapshot(connection: psycopg.Connection) -> None:
    connection.execute(
        """
        CREATE TABLE IF NOT EXISTS capability_standard_planning_snapshot (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            capability_standard_version_id BIGINT NOT NULL,
            l3_node_id BIGINT NOT NULL REFERENCES capability_node(id) ON DELETE RESTRICT,
            l3_code TEXT NOT NULL,
            l3_name TEXT NOT NULL,
            materials_text TEXT,
            resource_snapshot JSONB NOT NULL DEFAULT '[]'::jsonb,
            expected_output TEXT,
            estimated_hours TEXT,
            output_type TEXT,
            notes TEXT,
            source_workbook TEXT,
            source_sheet TEXT,
            source_row INT,
            source_type TEXT NOT NULL
                CHECK (source_type IN ('legacy_catalog_capture_v0009', 'version_publish')),
            source_hash TEXT NOT NULL,
            captured_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
            UNIQUE (capability_standard_version_id, l3_node_id)
        )
        """
    )
    # On fresh databases the table already exists (created by
    # create_catalog_schema without the FK, because the version table is created
    # later by migrations); on upgraded databases it is created here with the FK
    # inline.  The explicit FK below covers the fresh path idempotently.
    _add_fk(
        connection,
        "capability_standard_planning_snapshot",
        "planning_snapshot_version_fk",
        "FOREIGN KEY (capability_standard_version_id) "
        "REFERENCES capability_standard_version(id) ON DELETE RESTRICT",
    )
    connection.execute(
        """
        CREATE OR REPLACE FUNCTION guard_planning_snapshot_immutable()
        RETURNS TRIGGER AS $$
        DECLARE
            v_status TEXT;
        BEGIN
            SELECT status INTO v_status
            FROM capability_standard_version
            WHERE id = OLD.capability_standard_version_id;
            IF v_status IN ('已发布', '已归档') THEN
                RAISE EXCEPTION
                    'planning snapshot is immutable for published/archived versions'
                    USING ERRCODE = 'P0001';
            END IF;
            IF TG_OP = 'DELETE' THEN
                RETURN OLD;
            END IF;
            RETURN NEW;
        END;
        $$ LANGUAGE plpgsql
        """
    )
    connection.execute(
        """
        DROP TRIGGER IF EXISTS trg_planning_snapshot_immutable
        ON capability_standard_planning_snapshot
        """
    )
    connection.execute(
        """
        CREATE TRIGGER trg_planning_snapshot_immutable
        BEFORE UPDATE OR DELETE ON capability_standard_planning_snapshot
        FOR EACH ROW EXECUTE FUNCTION guard_planning_snapshot_immutable()
        """
    )


def _capture_legacy_planning_snapshots(connection: psycopg.Connection) -> None:
    """One-time compatibility capture for pre-v0009 published/archived versions.

    Values are taken from the current catalog at migration time and are
    explicitly tagged ``legacy_catalog_capture_v0009`` with the capture time and
    a hash over every frozen fact — never claimed to be the original
    publish-time snapshot.
    """
    versions = connection.execute(
        """
        SELECT id FROM capability_standard_version
        WHERE status IN ('已发布', '已归档')
        ORDER BY id
        """
    ).fetchall()
    for (version_id,) in versions:
        node_ids = connection.execute(
            """
            SELECT DISTINCT l3_node_id FROM capability_standard_item
            WHERE version_id = %s ORDER BY l3_node_id
            """,
            (version_id,),
        ).fetchall()
        for (node_id,) in node_ids:
            existing = connection.execute(
                """
                SELECT 1 FROM capability_standard_planning_snapshot
                WHERE capability_standard_version_id = %s AND l3_node_id = %s
                """,
                (version_id, node_id),
            ).fetchone()
            if existing is not None:
                continue
            row = connection.execute(
                """
                SELECT n.code, n.name, n.materials_text, n.expected_output,
                       n.estimated_hours, n.output_type, n.notes,
                       n.source_workbook, n.source_sheet, n.source_row
                FROM capability_node n
                WHERE n.id = %s AND n.node_type = 'L3'
                """,
                (node_id,),
            ).fetchone()
            if row is None:
                # Node no longer exists in the catalog: nothing to capture.
                continue
            resources = [
                {
                    "code": str(r[0]),
                    "name": str(r[1]),
                    "resource_type": str(r[2]),
                    "source": str(r[3]),
                    "purpose": str(r[4]),
                    "status": str(r[5]),
                }
                for r in connection.execute(
                    """
                    SELECT lr.material_code, lr.name, lr.material_type,
                           lr.source_text, lr.purpose, lr.status
                    FROM capability_node_resource cnr
                    JOIN learning_resource lr ON lr.id = cnr.resource_id
                    WHERE cnr.node_id = %s
                    ORDER BY lr.material_code
                    """,
                    (node_id,),
                ).fetchall()
            ]
            source_hash = planning_snapshot_hash(
                l3_node_id=int(node_id),
                l3_code=str(row[0]),
                l3_name=str(row[1]),
                materials_text=row[2],
                resources=resources,
                expected_output=row[3],
                estimated_hours=row[4],
                output_type=row[5],
                notes=row[6],
                source_workbook=row[7],
                source_sheet=row[8],
                source_row=row[9],
                source_type="legacy_catalog_capture_v0009",
            )
            connection.execute(
                """
                INSERT INTO capability_standard_planning_snapshot (
                    capability_standard_version_id, l3_node_id, l3_code, l3_name,
                    materials_text, resource_snapshot, expected_output,
                    estimated_hours, output_type, notes, source_workbook,
                    source_sheet, source_row, source_type, source_hash, captured_at
                )
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, NOW())
                """,
                (
                    version_id,
                    node_id,
                    row[0],
                    row[1],
                    row[2],
                    json.dumps(resources, ensure_ascii=False),
                    row[3],
                    row[4],
                    row[5],
                    row[6],
                    row[7],
                    row[8],
                    row[9],
                    "legacy_catalog_capture_v0009",
                    source_hash,
                ),
            )


