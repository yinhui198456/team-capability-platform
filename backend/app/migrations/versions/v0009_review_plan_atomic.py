"""v0009: Buddy Review atomic plan generation.

Additive, forward-only. Adds:

- ``capability_standard_planning_snapshot`` — immutable planning source per
  (version, L3), with a DB trigger blocking INSERT/UPDATE/DELETE once the
  version is published/archived (enabled only after the legacy backfill);
- ``legacy_catalog_capture_v0009`` backfill for pre-v0009 published/archived
  versions (explicitly marked as a one-time capture, never claimed to be the
  original publish-time snapshot);
- ``annual_growth_plan`` source columns (source_assessment_id, planning_source_type)
  with a partial unique index on the first-source assessment;
- ``plan_item`` full source snapshot columns, ``priority`` default removal,
  ``created_at``, CHECKs and a partial unique index on source_assessment_detail_id;
- ``assessment_review.reviewed_by_buddy_id`` (actual closer, legacy NULL ok);
- ``buddy_relationship`` canonical ``effective_date``/``expiry_date`` with a
  sync trigger (legacy columns cannot drift), an interval-overlap guard for
  primary relationships, and a second partial unique index;
- ``annual_plan_change_proposal`` + ``annual_plan_change_proposal_detail``
  (subsequent-assessment change proposals bound to the target plan), plus a
  pair of triggers forbidding the proposal source from being the target
  plan's first-source assessment (in both directions, INSERT and UPDATE);
- ``review_idempotency_key`` keyed by (buddy_id, idempotency_key).

No columns, tables or rows are removed or rewritten; historical data stays
readable.
"""

