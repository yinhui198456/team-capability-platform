    for constraint, expression in (
        (
            "plan_item_scope_type_check",
            "scope_type IS NULL OR scope_type IN ('current_required', 'target_progressive')",
        ),
        (
            "plan_item_standard_target_check",
            "standard_target_level IS NULL OR standard_target_level BETWEEN 1 AND 5",
        ),
        (
            "plan_item_adjusted_target_check",
            "adjusted_target_level IS NULL OR adjusted_target_level BETWEEN 1 AND 5",
        ),
        (
            "plan_item_effective_target_check",
            "effective_target_level IS NULL OR effective_target_level BETWEEN 1 AND 5",
        ),
        (
            "plan_item_job_level_snapshot_check",
            "standard_job_level_snapshot IS NULL OR standard_job_level_snapshot IN ('P4','P5','P6','P7','P8')",
        ),
        (
            "plan_item_member_level_snapshot_check",
            "(member_current_level_snapshot IS NULL OR member_current_level_snapshot IN ('P4','P5','P6','P7','P8'))"
            " AND (member_target_level_snapshot IS NULL OR member_target_level_snapshot IN ('P4','P5','P6','P7','P8'))",
        ),
        (
            "plan_item_quarter_check",
            "plan_quarter IS NULL OR plan_quarter IN ('Q1','Q2','Q3','Q4')",
        ),
        (
            "plan_item_month_check",
            "plan_month IS NULL OR plan_month BETWEEN 1 AND 12",
        ),
        (
            "plan_item_quarter_month_consistency",
            "plan_quarter IS NULL OR plan_month IS NULL"
            " OR (plan_quarter = 'Q1' AND plan_month BETWEEN 1 AND 3)"
            " OR (plan_quarter = 'Q2' AND plan_month BETWEEN 4 AND 6)"
            " OR (plan_quarter = 'Q3' AND plan_month BETWEEN 7 AND 9)"
            " OR (plan_quarter = 'Q4' AND plan_month BETWEEN 10 AND 12)",
        ),
        (
            "plan_item_source_type_check",
            "planning_source_type IS NULL OR planning_source_type IN ('assessment_approval')",
        ),
        (
            "plan_item_gap_value_check",
            "gap_value IS NULL OR gap_value >= 0",
        ),
    ):
        _add_check(connection, "plan_item", constraint, expression)
    # The completeness contract was tightened (P1-4/P1-2 2nd review): drop any
    # earlier definition of the guard so upgraded databases get the strong
    # version, then add it.  The 2nd-review contract adds scope_type, the
    # member level snapshots and the effective-target consistency rule
    # (effective is the adjusted target when adjusted, else the standard).
    connection.execute(
        "ALTER TABLE plan_item "
        "DROP CONSTRAINT IF EXISTS plan_item_approval_completeness"
    )
    _add_check(
        connection,
        "plan_item",
        "plan_item_approval_completeness",
        "planning_source_type IS DISTINCT FROM 'assessment_approval'"
        " OR ("
        "include_in_plan IS TRUE"
        " AND priority IS NOT NULL AND priority IN ('高', '中', '低')"
        " AND source_assessment_id IS NOT NULL"
        " AND source_assessment_detail_id IS NOT NULL"
        " AND capability_standard_version_id IS NOT NULL"
        " AND planning_snapshot_id IS NOT NULL"
        " AND l3_node_id IS NOT NULL"
        " AND l1_code IS NOT NULL AND l1_name IS NOT NULL"
        " AND l2_code IS NOT NULL AND l2_name IS NOT NULL"
        " AND l3_code IS NOT NULL AND l3_name IS NOT NULL"
        " AND scope_type IS NOT NULL"
        " AND standard_job_level_snapshot IS NOT NULL"
        " AND member_current_level_snapshot IS NOT NULL"
        " AND member_target_level_snapshot IS NOT NULL"
        " AND assessment_revision IS NOT NULL"
        " AND target_level = effective_target_level"
        " AND standard_target_level IS NOT NULL"
        " AND effective_target_level IS NOT NULL"
        " AND gap_value IS NOT NULL"
        " AND plan_quarter IS NOT NULL AND plan_month IS NOT NULL"
        " AND ("
        "   (adjusted_target_level IS NOT NULL"
        "    AND effective_target_level = adjusted_target_level)"
        "   OR"
        "   (adjusted_target_level IS NULL"
        "    AND effective_target_level = standard_target_level)"
        " )"
        ")",
    )
    connection.execute(
        """
        CREATE UNIQUE INDEX IF NOT EXISTS uniq_plan_item_source_detail
        ON plan_item(source_assessment_detail_id)
        WHERE source_assessment_detail_id IS NOT NULL
        """
    )


