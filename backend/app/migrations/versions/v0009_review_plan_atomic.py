def _enable_planning_provenance_immutability(connection: psycopg.Connection) -> None:
    """P1-A (3rd review): once a plan or plan item carries assessment_approval
    provenance, the discriminator and the source identity are immutable —
    they can never be downgraded to the legacy NULL branch (even together)
    and the source can never drift, including between two assessments of the
    same member/year."""
    connection.execute(
        """
        CREATE OR REPLACE FUNCTION guard_planning_provenance_immutable()
        RETURNS TRIGGER AS $$
        BEGIN
            IF TG_OP = 'UPDATE' THEN
                IF OLD.planning_source_type IS NOT NULL
                   AND NEW.planning_source_type IS DISTINCT FROM OLD.planning_source_type THEN
                    RAISE EXCEPTION
                        'planning provenance discriminator is immutable'
                        USING ERRCODE = 'P0001';
                END IF;
                IF OLD.source_assessment_id IS NOT NULL
                   AND NEW.source_assessment_id IS DISTINCT FROM OLD.source_assessment_id THEN
                    RAISE EXCEPTION
                        'planning source identity is immutable'
                        USING ERRCODE = 'P0001';
                END IF;
            END IF;
            RETURN NEW;
        END;
        $$ LANGUAGE plpgsql
        """
    )
    for table in ("annual_growth_plan", "plan_item"):
        connection.execute(
            f"DROP TRIGGER IF EXISTS trg_planning_provenance_immutable ON {table}"
        )
        connection.execute(
            f"""
            CREATE TRIGGER trg_planning_provenance_immutable
            BEFORE UPDATE ON {table}
            FOR EACH ROW EXECUTE FUNCTION guard_planning_provenance_immutable()
            """
        )


def _guard_proposal_source_against_plan_first_source(
    connection: psycopg.Connection,
) -> None:
    """4th review: the change proposal can never reuse the assessment that
    generated its target plan (the first approval source).  The formal plan
    is generated by the first approval; only subsequent assessments of the
    same member/year may generate adjustment proposals.  Both directions are
    guarded so the pair can never drift into an illegal state:

    - ``proposal.source_assessment_id`` must not equal the target plan's
      ``source_assessment_id`` (INSERT and UPDATE),
    - the plan's ``source_assessment_id`` (legacy NULL → non-NULL backfill)
      must not equal an existing proposal's source for the same plan.

    Both directions serialise on the target plan ROW itself (READ COMMITTED):
    the proposal guard reads the plan source under ``SELECT ... FOR UPDATE``
    and the plan-side UPDATE already holds the row lock, so the pair can
    never race into equal sources — the check always observes the latest
    committed value after any wait.  Existing rows are never scanned or
    rewritten — the guard only governs new writes.
    """
    connection.execute(
        """
        CREATE OR REPLACE FUNCTION guard_proposal_source_not_plan_first_source()
        RETURNS TRIGGER AS $$
        DECLARE
            plan_source BIGINT;
        BEGIN
            -- 5th review: serialise on the target plan ROW itself.  Both
            -- directions (proposal INSERT/UPDATE and the plan's legacy
            -- source backfill) contend for the same single row lock, so the
            -- read below always observes the latest committed plan source.
            -- A row lock (not an advisory key) is used on purpose: an
            -- advisory lock held here would deadlock against the INSERT's
            -- own foreign-key row lock when the plan-side UPDATE holds the
            -- row first (proposal waits on the row, backfill waits on the
            -- advisory key).
            SELECT source_assessment_id INTO plan_source
            FROM annual_growth_plan
            WHERE id = NEW.target_annual_growth_plan_id
            FOR UPDATE;
            IF plan_source IS NOT NULL
               AND NEW.source_assessment_id = plan_source THEN
                RAISE EXCEPTION
                    'change proposal source cannot be the target plan''s first source assessment'
                    USING ERRCODE = 'P0001';
            END IF;
            RETURN NEW;
        END;
        $$ LANGUAGE plpgsql
        """
    )
    connection.execute(
        "DROP TRIGGER IF EXISTS trg_proposal_source_not_plan_first_source "
        "ON annual_plan_change_proposal"
    )
    connection.execute(
        """
        CREATE TRIGGER trg_proposal_source_not_plan_first_source
        BEFORE INSERT OR UPDATE ON annual_plan_change_proposal
        FOR EACH ROW EXECUTE FUNCTION guard_proposal_source_not_plan_first_source()
        """
    )
    connection.execute(
        """
        CREATE OR REPLACE FUNCTION guard_plan_source_not_proposal_source()
        RETURNS TRIGGER AS $$
        BEGIN
            IF TG_OP = 'UPDATE' AND NEW.source_assessment_id IS NOT NULL THEN
                -- The UPDATE already holds the plan row lock; the proposal
                -- guard takes the same row lock (SELECT ... FOR UPDATE)
                -- before reading this column, so the EXISTS below sees every
                -- committed proposal for this plan.  Single lock object, no
                -- ordering differences, no deadlock.
                IF EXISTS (
                    SELECT 1 FROM annual_plan_change_proposal p
                    WHERE p.target_annual_growth_plan_id = NEW.id
                      AND p.source_assessment_id = NEW.source_assessment_id
                ) THEN
                    RAISE EXCEPTION
                        'plan first source cannot be an existing proposal source of the same plan'
                        USING ERRCODE = 'P0001';
                END IF;
            END IF;
            RETURN NEW;
        END;
        $$ LANGUAGE plpgsql
        """
    )
    connection.execute(
        "DROP TRIGGER IF EXISTS trg_plan_source_not_proposal_source "
        "ON annual_growth_plan"
    )
    connection.execute(
        """
        CREATE TRIGGER trg_plan_source_not_proposal_source
        BEFORE UPDATE ON annual_growth_plan
        FOR EACH ROW EXECUTE FUNCTION guard_plan_source_not_proposal_source()
        """
    )


