def _extend_buddy_relationship(connection: psycopg.Connection) -> None:
    connection.execute(
        "ALTER TABLE buddy_relationship ADD COLUMN IF NOT EXISTS effective_date DATE"
    )
    connection.execute(
        "ALTER TABLE buddy_relationship ADD COLUMN IF NOT EXISTS expiry_date DATE"
    )
    connection.execute(
        """
        UPDATE buddy_relationship
        SET effective_date = COALESCE(effective_from, CURRENT_DATE),
            expiry_date = effective_to
        WHERE effective_date IS NULL
        """
    )
    # effective_date is NOT NULL from this point on (idempotent guard below).
    connection.execute(
        """
        DO $$ BEGIN
            IF EXISTS (
                SELECT 1 FROM information_schema.columns
                WHERE table_name = 'buddy_relationship'
                  AND column_name = 'effective_date'
                  AND is_nullable = 'YES'
            ) THEN
                ALTER TABLE buddy_relationship ALTER COLUMN effective_date SET NOT NULL;
            END IF;
        END $$
        """
    )
    # Canonical dates are the single source of truth; legacy columns are synced
    # by the trigger so the two pairs can never drift.
    connection.execute(
        """
        CREATE OR REPLACE FUNCTION sync_buddy_relationship_dates()
        RETURNS TRIGGER AS $$
        BEGIN
            NEW.effective_from := NEW.effective_date;
            NEW.effective_to := NEW.expiry_date;
            RETURN NEW;
        END;
        $$ LANGUAGE plpgsql
        """
    )
    connection.execute(
        """
        DROP TRIGGER IF EXISTS trg_sync_buddy_relationship_dates
        ON buddy_relationship
        """
    )
    connection.execute(
        """
        CREATE TRIGGER trg_sync_buddy_relationship_dates
        BEFORE INSERT OR UPDATE ON buddy_relationship
        FOR EACH ROW EXECUTE FUNCTION sync_buddy_relationship_dates()
        """
    )
    # Interval-overlap guard: a member has at most one primary relationship
    # whose [effective_date, expiry_date] range overlaps any other's (open-ended
    # ranges count as infinite).  Adjacent ranges (expiry + 1 day = next start)
    # are allowed.
    connection.execute(
        """
        CREATE OR REPLACE FUNCTION guard_buddy_primary_overlap()
        RETURNS TRIGGER AS $$
        DECLARE
            other_id BIGINT;
        BEGIN
            IF NOT NEW.is_primary THEN
                RETURN NEW;
            END IF;
            SELECT id INTO other_id
            FROM buddy_relationship
            WHERE member_id = NEW.member_id
              AND is_primary = TRUE
              AND id <> NEW.id
              AND NEW.effective_date <= COALESCE(expiry_date, DATE '9999-12-31')
              AND COALESCE(effective_date, DATE '0001-01-01')
                  <= COALESCE(NEW.expiry_date, DATE '9999-12-31')
            LIMIT 1;
            IF other_id IS NOT NULL THEN
                RAISE EXCEPTION
                    'primary buddy relationship overlaps an existing range'
                    USING ERRCODE = 'P0001';
            END IF;
            RETURN NEW;
        END;
        $$ LANGUAGE plpgsql
        """
    )
    connection.execute(
        """
        DROP TRIGGER IF EXISTS trg_buddy_primary_overlap
        ON buddy_relationship
        """
    )
    connection.execute(
        """
        CREATE TRIGGER trg_buddy_primary_overlap
        BEFORE INSERT OR UPDATE ON buddy_relationship
        FOR EACH ROW EXECUTE FUNCTION guard_buddy_primary_overlap()
        """
    )
    # Concurrent-creation last line: at most one open-ended primary per member.
    connection.execute(
        """
        CREATE UNIQUE INDEX IF NOT EXISTS uniq_active_primary_buddy_v2
        ON buddy_relationship(member_id)
        WHERE is_primary = TRUE AND expiry_date IS NULL
        """
    )


def _create_change_proposal_tables(connection: psycopg.Connection) -> None:
    connection.execute(
        """
        CREATE TABLE IF NOT EXISTS annual_plan_change_proposal (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            member_id BIGINT NOT NULL REFERENCES tcp_user(id) ON DELETE RESTRICT,
            year INT NOT NULL,
            source_assessment_id BIGINT NOT NULL
                REFERENCES assessment(id) ON DELETE RESTRICT,
            target_annual_growth_plan_id BIGINT NOT NULL
                REFERENCES annual_growth_plan(id) ON DELETE RESTRICT,
            status TEXT NOT NULL DEFAULT '待处理'
                CHECK (status IN ('待处理')),
            created_by BIGINT NOT NULL REFERENCES tcp_user(id) ON DELETE RESTRICT,
            summary JSONB NOT NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
            UNIQUE (source_assessment_id)
        )
        """
    )
    connection.execute(
        """
        CREATE TABLE IF NOT EXISTS annual_plan_change_proposal_detail (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            proposal_id BIGINT NOT NULL
                REFERENCES annual_plan_change_proposal(id) ON DELETE CASCADE,
            source_assessment_detail_id BIGINT NOT NULL
                REFERENCES assessment_detail(id) ON DELETE RESTRICT,
            assessment_id BIGINT NOT NULL,
            l3_node_id BIGINT NOT NULL,
            l1_code TEXT NOT NULL,
            l1_name TEXT NOT NULL,
            l2_code TEXT NOT NULL,
            l2_name TEXT NOT NULL,
            l3_code TEXT NOT NULL,
            l3_name TEXT NOT NULL,
            scope_type TEXT CHECK (
                scope_type IS NULL
                OR scope_type IN ('current_required', 'target_progressive')
            ),
            current_level INT CHECK (current_level IS NULL OR current_level BETWEEN 0 AND 5),
            standard_target_level INT CHECK (
                standard_target_level IS NULL OR standard_target_level BETWEEN 1 AND 5
            ),
            adjusted_target_level INT CHECK (
                adjusted_target_level IS NULL OR adjusted_target_level BETWEEN 1 AND 5
            ),
            effective_target_level INT CHECK (
                effective_target_level IS NULL OR effective_target_level BETWEEN 1 AND 5
            ),
            gap_value INT CHECK (gap_value IS NULL OR gap_value >= 0),
            member_priority TEXT CHECK (
                member_priority IS NULL OR member_priority IN ('高', '中', '低', '暂缓')
            ),
            include_in_plan BOOLEAN,
            plan_quarter TEXT CHECK (
                plan_quarter IS NULL OR plan_quarter IN ('Q1', 'Q2', 'Q3', 'Q4')
            ),
            plan_month INT CHECK (plan_month IS NULL OR plan_month BETWEEN 1 AND 12),
            standard_job_level_snapshot TEXT CHECK (
                standard_job_level_snapshot IS NULL
                OR standard_job_level_snapshot IN ('P4', 'P5', 'P6', 'P7', 'P8')
            ),
            member_current_level_snapshot TEXT CHECK (
                member_current_level_snapshot IS NULL
                OR member_current_level_snapshot IN ('P4', 'P5', 'P6', 'P7', 'P8')
            ),
            member_target_level_snapshot TEXT CHECK (
                member_target_level_snapshot IS NULL
                OR member_target_level_snapshot IN ('P4', 'P5', 'P6', 'P7', 'P8')
            ),
            capability_standard_version_id BIGINT NOT NULL,
            planning_snapshot_id BIGINT,
            assessment_revision BIGINT NOT NULL,
            planning_source_type TEXT NOT NULL DEFAULT 'assessment_approval'
                CHECK (planning_source_type IN ('assessment_approval')),
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
            UNIQUE (source_assessment_detail_id),
            CHECK (
                plan_quarter IS NULL OR plan_month IS NULL
                OR (plan_quarter = 'Q1' AND plan_month BETWEEN 1 AND 3)
                OR (plan_quarter = 'Q2' AND plan_month BETWEEN 4 AND 6)
                OR (plan_quarter = 'Q3' AND plan_month BETWEEN 7 AND 9)
                OR (plan_quarter = 'Q4' AND plan_month BETWEEN 10 AND 12)
            )
        )
        """
    )


