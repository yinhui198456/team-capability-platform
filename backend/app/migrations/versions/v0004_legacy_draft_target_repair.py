import psycopg

from ...catalog.standard_targets import resolve_standard_target

JOB_LEVELS = ("P4", "P5", "P6", "P7", "P8")


def _create_schema(connection: psycopg.Connection) -> None:
    connection.execute(
        """
        CREATE TABLE IF NOT EXISTS capability_standard_version (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            model_id BIGINT NOT NULL REFERENCES capability_model(id) ON DELETE RESTRICT,
            version_no INT NOT NULL CHECK (version_no > 0),
            label TEXT NOT NULL,
            status TEXT NOT NULL CHECK (status IN ('草稿', '已发布', '已归档')),
            based_on_version_id BIGINT
                REFERENCES capability_standard_version(id) ON DELETE RESTRICT,
            revision BIGINT NOT NULL DEFAULT 1,
            created_by BIGINT,
            published_by BIGINT,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
            published_at TIMESTAMPTZ,
            UNIQUE (model_id, version_no)
        )
        """
    )
    connection.execute(
        """
        CREATE UNIQUE INDEX IF NOT EXISTS unique_published_capability_standard
        ON capability_standard_version(model_id)
        WHERE status = '已发布'
        """
    )
    connection.execute(
        """
        CREATE TABLE IF NOT EXISTS capability_standard_item (
            version_id BIGINT NOT NULL
                REFERENCES capability_standard_version(id) ON DELETE RESTRICT,
            l1_code TEXT NOT NULL,
            l1_name TEXT NOT NULL,
            l2_code TEXT NOT NULL,
            l2_name TEXT NOT NULL,
            l3_code TEXT NOT NULL,
            l3_name TEXT NOT NULL,
            job_level TEXT NOT NULL CHECK (job_level IN ('P4', 'P5', 'P6', 'P7', 'P8')),
            applicable BOOLEAN NOT NULL,
            target_level INT CHECK (
                target_level IS NULL OR target_level BETWEEN 1 AND 5
            ),
            source TEXT NOT NULL CHECK (source IN ('explicit', 'legacy_derived')),
            PRIMARY KEY (version_id, l3_code, job_level),
            CHECK (
                (applicable = TRUE AND target_level BETWEEN 1 AND 5)
                OR (applicable = FALSE AND target_level IS NULL)
            )
        )
        """
    )
    for definition in (
        "member_current_level_snapshot TEXT",
        "member_target_level_snapshot TEXT",
        "capability_standard_version_id BIGINT",
    ):
        connection.execute(
            f"ALTER TABLE assessment ADD COLUMN IF NOT EXISTS {definition}"
        )
    connection.execute(
        """
        CREATE TABLE IF NOT EXISTS assessment_draft_target_repair_audit (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            assessment_id BIGINT NOT NULL REFERENCES assessment(id) ON DELETE RESTRICT,
            actor_user_id BIGINT NOT NULL,
            old_revision BIGINT NOT NULL,
            new_revision BIGINT NOT NULL,
            old_current_level_source TEXT,
            new_current_level_source TEXT NOT NULL,
            old_target_level_source TEXT,
            new_target_level_source TEXT NOT NULL,
            old_standard_version_id BIGINT,
            new_standard_version_id BIGINT NOT NULL,
            result TEXT NOT NULL CHECK (result = 'repaired'),
            summary JSONB NOT NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )
        """
    )
    connection.execute(
        """
        CREATE INDEX IF NOT EXISTS idx_assessment_draft_target_repair_audit_assessment
        ON assessment_draft_target_repair_audit(assessment_id, created_at DESC)
        """
    )
    constraints = {
        "capability_standard_version_created_by_fkey": """
            FOREIGN KEY (created_by) REFERENCES tcp_user(id) ON DELETE SET NULL
        """,
        "capability_standard_version_published_by_fkey": """
            FOREIGN KEY (published_by) REFERENCES tcp_user(id) ON DELETE SET NULL
        """,
        "assessment_capability_standard_version_id_fkey": """
            FOREIGN KEY (capability_standard_version_id)
            REFERENCES capability_standard_version(id) ON DELETE RESTRICT
        """,
        "assessment_draft_target_repair_audit_actor_user_id_fkey": """
            FOREIGN KEY (actor_user_id) REFERENCES tcp_user(id) ON DELETE RESTRICT
        """,
        "assessment_draft_target_repair_audit_old_standard_version_id_fkey": """
            FOREIGN KEY (old_standard_version_id)
            REFERENCES capability_standard_version(id) ON DELETE RESTRICT
        """,
        "assessment_draft_target_repair_audit_new_standard_version_id_fkey": """
            FOREIGN KEY (new_standard_version_id)
            REFERENCES capability_standard_version(id) ON DELETE RESTRICT
        """,
    }
    tables = {
        "capability_standard_version_created_by_fkey": "capability_standard_version",
        "capability_standard_version_published_by_fkey": "capability_standard_version",
        "assessment_capability_standard_version_id_fkey": "assessment",
        "assessment_draft_target_repair_audit_actor_user_id_fkey": (
            "assessment_draft_target_repair_audit"
        ),
        "assessment_draft_target_repair_audit_old_standard_version_id_fkey": (
            "assessment_draft_target_repair_audit"
        ),
        "assessment_draft_target_repair_audit_new_standard_version_id_fkey": (
            "assessment_draft_target_repair_audit"
        ),
    }
    for name, definition in constraints.items():
        connection.execute(
            f"""
            DO $$
            BEGIN
                IF NOT EXISTS (
                    SELECT 1 FROM pg_constraint WHERE conname = '{name}'
                ) THEN
                    ALTER TABLE {tables[name]}
                    ADD CONSTRAINT {name} {definition};
                END IF;
            END
            $$
            """
        )


def _validate_matrix(rows: list[tuple[object, ...]]) -> None:
    by_l3: dict[str, list[tuple[bool, int | None]]] = {}
    for l3_code, job_level, applicable, target_level in rows:
        by_l3.setdefault(str(l3_code), []).append((bool(applicable), target_level))
        if str(job_level) not in JOB_LEVELS:
            raise ValueError(f"invalid Legacy Baseline job level for {l3_code}")
    for l3_code, items in by_l3.items():
        if len(items) != len(JOB_LEVELS):
            raise ValueError(f"incomplete Legacy Baseline matrix for {l3_code}")
        seen_applicable = False
        last_target: int | None = None
        for applicable, target_level in items:
            if not applicable:
                if seen_applicable or target_level is not None:
                    raise ValueError(f"non-monotonic Legacy Baseline for {l3_code}")
                continue
            if target_level is None:
                raise ValueError(f"missing Legacy Baseline target for {l3_code}")
            if last_target is not None and target_level < last_target:
                raise ValueError(f"decreasing Legacy Baseline target for {l3_code}")
            seen_applicable = True
            last_target = target_level


def _publish_legacy_baseline(connection: psycopg.Connection, model_id: int) -> None:
    existing = connection.execute(
        """
        SELECT id FROM capability_standard_version
        WHERE model_id = %s AND version_no = 1
        """,
        (model_id,),
    ).fetchone()
    if existing is not None:
        return

    source_rows = connection.execute(
        """
        SELECT l1.code, l1.name, l2.code, l2.name, l3.code, l3.name,
               l3.recommended_start_level
        FROM capability_node l3
        JOIN capability_node l2 ON l2.id = l3.parent_node_id
        JOIN capability_node l1 ON l1.id = l2.parent_node_id
        WHERE l3.model_id = %s AND l3.node_type = 'L3' AND l3.enabled = TRUE
        ORDER BY l3.code
        """,
        (model_id,),
    ).fetchall()
    items: list[tuple[object, ...]] = []
    validation_rows: list[tuple[object, ...]] = []
    for (
        l1_code,
        l1_name,
        l2_code,
        l2_name,
        l3_code,
        l3_name,
        start_level,
    ) in source_rows:
        if start_level is None:
            raise ValueError(f"missing recommended_start_level for {l3_code}")
        for job_level in JOB_LEVELS:
            override = connection.execute(
                """
                SELECT o.target_level, o.node_id IS NOT NULL
                FROM capability_node n
                LEFT JOIN capability_standard_target_override o
                  ON o.node_id = n.id AND o.job_level = %s
                WHERE n.model_id = %s AND n.code = %s AND n.node_type = 'L3'
                """,
                (job_level, model_id, l3_code),
            ).fetchone()
            override_value, override_present = override if override else (None, False)
            resolved = resolve_standard_target(
                str(job_level),
                str(start_level),
                override_present=bool(override_present),
                override_value=override_value,
            )
            validation_rows.append(
                (l3_code, job_level, resolved.applicable, resolved.target_level)
            )
            items.append(
                (
                    l1_code,
                    l1_name,
                    l2_code,
                    l2_name,
                    l3_code,
                    l3_name,
                    job_level,
                    resolved.applicable,
                    resolved.target_level,
                )
            )
    _validate_matrix(validation_rows)
    version = connection.execute(
        """
        INSERT INTO capability_standard_version (
            model_id, version_no, label, status, revision, published_at
        ) VALUES (%s, 1, 'Legacy Baseline v1', '已发布', 1, NOW())
        RETURNING id
        """,
        (model_id,),
    ).fetchone()
    assert version is not None
    version_id = version[0]
    with connection.cursor() as cursor:
        cursor.executemany(
            """
            INSERT INTO capability_standard_item (
                version_id, l1_code, l1_name, l2_code, l2_name, l3_code, l3_name,
                job_level, applicable, target_level, source
            ) VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, 'legacy_derived')
            """,
            [(version_id, *item) for item in items],
        )


def upgrade(connection: psycopg.Connection) -> None:
    _create_schema(connection)
    model_rows = connection.execute(
        "SELECT id FROM capability_model ORDER BY id"
    ).fetchall()
    for (model_id,) in model_rows:
        _publish_legacy_baseline(connection, int(model_id))
