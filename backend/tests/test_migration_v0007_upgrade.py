def _detail_columns(connection: psycopg.Connection) -> set[str]:
    rows = connection.execute(
        "SELECT column_name FROM information_schema.columns "
        "WHERE table_name = 'assessment_detail'"
    ).fetchall()
    return {str(row[0]) for row in rows}


def _applied_versions(connection: psycopg.Connection) -> list[str]:
    rows = connection.execute(
        "SELECT version FROM schema_migration ORDER BY applied_at, version"
    ).fetchall()
    return [str(row[0]) for row in rows]


