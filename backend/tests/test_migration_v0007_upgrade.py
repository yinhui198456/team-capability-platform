def test_registry_order_covers_v0001_through_v0008() -> None:
    """The migration chain registers v0001→v0008 in order (v0007 present)."""
    assert [version for version, _ in MIGRATIONS] == _EXPECTED_VERSIONS


def test_pre_v0007_database_really_lacks_new_contract(
    pre_v0007_db: psycopg.Connection,
) -> None:
    connection = pre_v0007_db
    columns = _detail_columns(connection)
    assert "member_priority" not in columns
    assert "include_in_plan" not in columns
    assert "plan_quarter" not in columns
    assert "plan_month" not in columns
    assert _applied_versions(connection) == _EXPECTED_VERSIONS[:6]

    # Old CHECK: current_level=0 is rejected pre-v0007.
    draft_id = int(
        connection.execute("SELECT id FROM assessment WHERE year = 2025").fetchone()[0]
    )
    with pytest.raises(psycopg.errors.CheckViolation):
        with connection.transaction():
            connection.execute(
                "INSERT INTO assessment_detail (assessment_id, l3_code, "
                "current_level, plan_candidate) "
                "VALUES (%s, 'C01.01.03', 0, FALSE)",
                (draft_id,),
            )
    # gap.priority is still NOT NULL pre-v0007.
    archived_id = int(
        connection.execute("SELECT id FROM assessment WHERE year = 2024").fetchone()[0]
    )
    with pytest.raises(psycopg.errors.NotNullViolation):
        with connection.transaction():
            connection.execute(
                "INSERT INTO gap (assessment_id, l3_code, current_level, "
                "target_level, gap_value, priority, plan_candidate) "
                "VALUES (%s, 'C01.01.09', 1, 3, 2, NULL, FALSE)",
                (archived_id,),
            )
    connection.commit()


def test_upgrade_to_v0008_and_lifespan(pre_v0007_db: psycopg.Connection) -> None:
    connection = pre_v0007_db

    # ── Run the production migration runner (v0007 → latest). ─────────
    run_migrations(connection)
    connection.commit()

    # Order + run-once.
    applied = _applied_versions(connection)
    assert applied == _EXPECTED_VERSIONS
    assert len(set(applied)) == len(applied)

    # New columns exist now.
    columns = _detail_columns(connection)
    for column in (
        "member_priority",
        "include_in_plan",
        "plan_quarter",
        "plan_month",
    ):
        assert column in columns

    # ── Legacy data readable, values intact, nothing fabricated. ──────
    archived = get_assessment(
        connection,
        int(
            connection.execute(
                "SELECT id FROM assessment WHERE year = 2024"
            ).fetchone()[0]
        ),
    )
    row = next(d for d in archived["details"] if d["l3_code"] == "C01.01.01")
    assert row["current_level"] == 2
    assert row["plan_candidate"] is True  # legacy read-only value preserved
    assert row["member_priority"] is None  # NOT fabricated from gap.priority
    assert row["include_in_plan"] is None  # NOT fabricated from plan_candidate
    assert row["plan_quarter"] is None
    assert row["plan_month"] is None

    # Summary must not present legacy auto-values as member decisions.
    summary = _get_gap_summary(connection, int(archived["id"]))
    assert summary["total_gaps"] == 1
    assert summary["in_plan"] == 0
    assert summary["high_priority"] == 0
    assert summary["on_hold"] == 0

    # Legacy gap row keeps its historical priority (read-only).
    gap_row = connection.execute(
        "SELECT priority, plan_candidate FROM gap WHERE l3_code = 'C01.01.01'"
    ).fetchone()
    assert gap_row == ("高", True)

    # Legacy unassessed draft row stays NULL.
    draft = get_assessment(
        connection,
        int(
            connection.execute(
                "SELECT id FROM assessment WHERE year = 2025"
            ).fetchone()[0]
        ),
    )
    draft_row = draft["details"][0]
    assert draft_row["current_level"] is None
    assert draft_row["member_priority"] is None
    assert draft_row["include_in_plan"] is None

    # ── New constraints are active. ────────────────────────────────────
    detail_id = int(row["id"])
    # current_level=0 is legal now (0 = 未接触, distinct from NULL).
    with connection.transaction():
        connection.execute(
            "UPDATE assessment_detail SET current_level = 0 WHERE id = %s",
            (detail_id,),
        )
    # Invalid priority rejected.
    with pytest.raises(psycopg.errors.CheckViolation):
        with connection.transaction():
            connection.execute(
                "UPDATE assessment_detail SET member_priority = '无效' "
                "WHERE id = %s",
                (detail_id,),
            )
    # include_in_plan=TRUE without quarter/month rejected (v0007).
    with pytest.raises(psycopg.errors.CheckViolation):
        with connection.transaction():
            connection.execute(
                "UPDATE assessment_detail SET include_in_plan = TRUE " "WHERE id = %s",
                (detail_id,),
            )
    # include_in_plan=NULL with plan_quarter set rejected (v0008).
    with pytest.raises(psycopg.errors.CheckViolation):
        with connection.transaction():
            connection.execute(
                "UPDATE assessment_detail SET plan_quarter = 'Q1' WHERE id = %s",
                (detail_id,),
            )
    connection.commit()

    # ── Idempotent re-run. ─────────────────────────────────────────────
    run_migrations(connection)
    connection.commit()
    assert _applied_versions(connection) == _EXPECTED_VERSIONS

    # ── Full application lifespan boots on the upgraded database. ──────
    from app.main import app as fastapi_app
    from app.main import lifespan

    async def _boot() -> None:
        async with lifespan(fastapi_app):
            pass

    asyncio.run(_boot())

    # Lifespan ran migrations idempotently and left legacy data intact.
    assert _applied_versions(connection) == _EXPECTED_VERSIONS
    row_after = connection.execute(
        "SELECT current_level, member_priority, include_in_plan "
        "FROM assessment_detail WHERE id = %s",
        (detail_id,),
    ).fetchone()
    assert row_after == (0, None, None)

    # A second boot is also idempotent.
    asyncio.run(_boot())
    assert _applied_versions(connection) == _EXPECTED_VERSIONS
